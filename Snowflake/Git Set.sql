USE ROLE ACCOUNTADMIN;
USE DATABASE FINANCIAL;
CREATE SCHEMA IF NOT EXISTS FINANCIAL.GIT_REPOS;
USE SCHEMA FINANCIAL.GIT_REPOS;

-- 1. Store your Git username and Personal Access Token securely
CREATE OR REPLACE SECRET FINANCIAL.GIT_REPOS.MY_GIT_SECRET
  TYPE = password
  USERNAME = 'hillelmorris'
  PASSWORD = '<YOUR_GITHUB_PAT>';

-- 2. Authorize Snowflake to connect to your GitHub account
CREATE OR REPLACE API INTEGRATION MY_GIT_API_INTEGRATION
  API_PROVIDER = git_https_api
  API_ALLOWED_PREFIXES = ('https://github.com/hillelmorris')
  ALLOWED_AUTHENTICATION_SECRETS = (FINANCIAL.GIT_REPOS.MY_GIT_SECRET)
  ENABLED = TRUE;

-- 3. Create the Git Repository link in Snowflake
CREATE OR REPLACE GIT REPOSITORY FINANCIAL.GIT_REPOS.GIT_HILLEL_MORRIS_REPO
  API_INTEGRATION = MY_GIT_API_INTEGRATION
  GIT_CREDENTIALS = FINANCIAL.GIT_REPOS.MY_GIT_SECRET
  ORIGIN = 'https://github.com/hillelmorris/Git-Hillel-Morris.git';

-- Verify the connection and see your new Snowflake folder
ALTER GIT REPOSITORY FINANCIAL.GIT_REPOS.GIT_HILLEL_MORRIS_REPO FETCH;
LIST @FINANCIAL.GIT_REPOS.GIT_HILLEL_MORRIS_REPO/branches/main/Snowflake/;