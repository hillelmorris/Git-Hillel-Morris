USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;
USE DATABASE FINANCIAL;

CREATE SCHEMA IF NOT EXISTS FINANCIAL.SILVER;
USE SCHEMA FINANCIAL.SILVER;

-- ============================================================================
-- 1. DIMENSION TABLES (With Primary Keys)
-- ============================================================================

-- 1A. Accounts Dimension
CREATE OR REPLACE TABLE FINANCIAL.SILVER.DIM_ACCOUNTS (
    ACCOUNT_ID      VARCHAR(32)   NOT NULL,
    ACCOUNT_NAME    VARCHAR(255)  NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_ACCOUNTS PRIMARY KEY (ACCOUNT_ID)
);

-- 1B. Payees Dimension
CREATE OR REPLACE TABLE FINANCIAL.SILVER.DIM_PAYEES (
    PAYEE_ID        VARCHAR(32)   NOT NULL,
    PAYEE_NAME      VARCHAR(255)  NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_PAYEES PRIMARY KEY (PAYEE_ID)
);

-- 1C. Categories Dimension
CREATE OR REPLACE TABLE FINANCIAL.SILVER.DIM_CATEGORIES (
    CATEGORY_ID     VARCHAR(32)   NOT NULL,
    CATEGORY_NAME   VARCHAR(255)  NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DIM_CATEGORIES PRIMARY KEY (CATEGORY_ID)
);

-- ============================================================================
-- 2. FACT TABLES (With Primary Keys & Foreign Keys)
-- ============================================================================

-- 2A. Transaction Header Fact Table (1 row per bank/card transaction)
CREATE OR REPLACE TABLE FINANCIAL.SILVER.FACT_TRANSACTIONS (
    TRANSACTION_ID        VARCHAR(32)   NOT NULL,
    ACCOUNT_ID            VARCHAR(32)   NOT NULL,
    PAYEE_ID              VARCHAR(32)   NOT NULL,
    TRANSACTION_DATE      DATE          NOT NULL,
    CHECK_NUM             VARCHAR(100),
    DEBIT_AMOUNT          NUMBER(12, 2) NOT NULL DEFAULT 0,
    CREDIT_AMOUNT         NUMBER(12, 2) NOT NULL DEFAULT 0,
    NET_AMOUNT            NUMBER(12, 2) NOT NULL DEFAULT 0,
    TOTAL_CATEGORY_AMOUNT NUMBER(12, 2) NOT NULL DEFAULT 0,
    RECEIPT_STATUS        VARCHAR(50),
    MEMO                  VARCHAR(1000),
    STATEMENT_DATES       VARCHAR(100),
    CLEARED_TYPE          VARCHAR(100),
    RECONCILED_AT         DATE,
    REVIEW_FLAG           VARCHAR(50),
    _SOURCE_FILE          VARCHAR(255),
    _INGESTED_AT          TIMESTAMP_LTZ,
    CONSTRAINT PK_FACT_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID),
    CONSTRAINT FK_TRANSACTIONS_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES FINANCIAL.SILVER.DIM_ACCOUNTS (ACCOUNT_ID),
    CONSTRAINT FK_TRANSACTIONS_PAYEE   FOREIGN KEY (PAYEE_ID)   REFERENCES FINANCIAL.SILVER.DIM_PAYEES (PAYEE_ID)
);

-- 2B. Activity Splits Fact Table (Unpivots Category1..6 & Amount1..6 into 1 row per split)
CREATE OR REPLACE TABLE FINANCIAL.SILVER.FACT_ACTIVITY_SPLITS (
    ACTIVITY_SPLIT_ID     VARCHAR(32)   NOT NULL,
    TRANSACTION_ID        VARCHAR(32)   NOT NULL,
    ACCOUNT_ID            VARCHAR(32)   NOT NULL,
    PAYEE_ID              VARCHAR(32)   NOT NULL,
    CATEGORY_ID           VARCHAR(32)   NOT NULL,
    SPLIT_NUMBER          NUMBER(2, 0)  NOT NULL,
    TRANSACTION_DATE      DATE          NOT NULL,
    SPLIT_AMOUNT          NUMBER(12, 2) NOT NULL DEFAULT 0,
    MEMO                  VARCHAR(1000),
    CONSTRAINT PK_FACT_ACTIVITY_SPLITS PRIMARY KEY (ACTIVITY_SPLIT_ID),
    CONSTRAINT FK_SPLITS_TRANSACTION FOREIGN KEY (TRANSACTION_ID) REFERENCES FINANCIAL.SILVER.FACT_TRANSACTIONS (TRANSACTION_ID),
    CONSTRAINT FK_SPLITS_ACCOUNT     FOREIGN KEY (ACCOUNT_ID)     REFERENCES FINANCIAL.SILVER.DIM_ACCOUNTS (ACCOUNT_ID),
    CONSTRAINT FK_SPLITS_PAYEE       FOREIGN KEY (PAYEE_ID)       REFERENCES FINANCIAL.SILVER.DIM_PAYEES (PAYEE_ID),
    CONSTRAINT FK_SPLITS_CATEGORY    FOREIGN KEY (CATEGORY_ID)    REFERENCES FINANCIAL.SILVER.DIM_CATEGORIES (CATEGORY_ID)
);

-- ============================================================================
-- 3. STORED PROCEDURE TO POPULATE / REFRESH ALL SILVER TABLES
-- ============================================================================

CREATE OR REPLACE PROCEDURE FINANCIAL.SILVER.SP_REFRESH_SILVER_LAYER()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN
    -- Helper function logic inline: cleans '$ 1,234.56', '$ -', and '$ (21.99)' into signed decimals
    CREATE OR REPLACE TEMPORARY TABLE FINANCIAL.SILVER.TMP_STAGED_BRONZE AS
    WITH base AS (
        SELECT
            ROW_NUMBER() OVER (ORDER BY _INGESTED_AT, ACCOUNT, DATE_RAW, PAYEE) AS ROW_SEQ,
            COALESCE(NULLIF(TRIM(ACCOUNT), ''), 'Unknown Account') AS ACCOUNT_NAME,
            TRY_TO_DATE(TRIM(DATE_RAW), 'DY, MON DD, YYYY') AS TRANSACTION_DATE,
            COALESCE(NULLIF(TRIM(PAYEE), ''), 'Unknown Payee') AS PAYEE_NAME,
            NULLIF(TRIM(CHECK_NUM), '') AS CHECK_NUM,
            -- Parse Debit
            COALESCE(TRY_TO_NUMBER(
                CASE 
                    WHEN DEBIT LIKE '%(%' THEN '-' || REGEXP_REPLACE(DEBIT, '[^0-9.]', '')
                    ELSE REGEXP_REPLACE(DEBIT, '[^0-9.-]', '')
                END, 12, 2), 0) AS DEBIT_AMOUNT,
            -- Parse Credit
            COALESCE(TRY_TO_NUMBER(
                CASE 
                    WHEN CREDIT LIKE '%(%' THEN '-' || REGEXP_REPLACE(CREDIT, '[^0-9.]', '')
                    ELSE REGEXP_REPLACE(CREDIT, '[^0-9.-]', '')
                END, 12, 2), 0) AS CREDIT_AMOUNT,
            -- Parse Total Categories
            COALESCE(TRY_TO_NUMBER(
                CASE 
                    WHEN TOTAL_CATEGORIES LIKE '%(%' THEN '-' || REGEXP_REPLACE(TOTAL_CATEGORIES, '[^0-9.]', '')
                    ELSE REGEXP_REPLACE(TOTAL_CATEGORIES, '[^0-9.-]', '')
                END, 12, 2), 0) AS TOTAL_CATEGORY_AMOUNT,
            NULLIF(TRIM(RECEIPT), '') AS RECEIPT_STATUS,
            NULLIF(TRIM(MEMO), '') AS MEMO,
            NULLIF(TRIM(STATEMENT_DATES), '') AS STATEMENT_DATES,
            NULLIF(TRIM(CLEARED_TYPE), '') AS CLEARED_TYPE,
            TRY_TO_DATE(TRIM(RECONCILIATION_TIMESTAMP), 'MM/DD/YYYY') AS RECONCILED_AT,
            NULLIF(TRIM(REVIEW), '') AS REVIEW_FLAG,
            NULLIF(TRIM(CATEGORY1), '') AS CATEGORY1, AMOUNT1,
            NULLIF(TRIM(CATEGORY2), '') AS CATEGORY2, AMOUNT2,
            NULLIF(TRIM(CATEGORY3), '') AS CATEGORY3, AMOUNT3,
            NULLIF(TRIM(CATEGORY4), '') AS CATEGORY4, AMOUNT4,
            NULLIF(TRIM(CATEGORY5), '') AS CATEGORY5, AMOUNT5,
            NULLIF(TRIM(CATEGORY6), '') AS CATEGORY6, AMOUNT6,
            _SOURCE_FILE,
            _INGESTED_AT
        FROM FINANCIAL.BRONZE.COMBINED_ACCOUNTS_RAW
        WHERE TRIM(DATE_RAW) IS NOT NULL AND TRIM(DATE_RAW) <> ''
    )
    SELECT
        MD5(CONCAT_WS('|', ACCOUNT_NAME, TO_VARCHAR(TRANSACTION_DATE), PAYEE_NAME, TO_VARCHAR(DEBIT_AMOUNT), TO_VARCHAR(CREDIT_AMOUNT), TO_VARCHAR(ROW_SEQ))) AS TRANSACTION_ID,
        MD5(UPPER(ACCOUNT_NAME)) AS ACCOUNT_ID,
        MD5(UPPER(PAYEE_NAME)) AS PAYEE_ID,
        *
    FROM base
    WHERE TRANSACTION_DATE IS NOT NULL;

    -- 3A. Populate DIM_ACCOUNTS
    TRUNCATE TABLE FINANCIAL.SILVER.DIM_ACCOUNTS;
    INSERT INTO FINANCIAL.SILVER.DIM_ACCOUNTS (ACCOUNT_ID, ACCOUNT_NAME)
    SELECT DISTINCT
        ACCOUNT_ID,
        MIN(ACCOUNT_NAME) AS ACCOUNT_NAME
    FROM FINANCIAL.SILVER.TMP_STAGED_BRONZE
    GROUP BY ACCOUNT_ID;

    -- 3B. Populate DIM_PAYEES
    TRUNCATE TABLE FINANCIAL.SILVER.DIM_PAYEES;
    INSERT INTO FINANCIAL.SILVER.DIM_PAYEES (PAYEE_ID, PAYEE_NAME)
    SELECT DISTINCT
        PAYEE_ID,
        MIN(PAYEE_NAME) AS PAYEE_NAME
    FROM FINANCIAL.SILVER.TMP_STAGED_BRONZE
    GROUP BY PAYEE_ID;

    -- 3C. Populate FACT_TRANSACTIONS
    TRUNCATE TABLE FINANCIAL.SILVER.FACT_TRANSACTIONS;
    INSERT INTO FINANCIAL.SILVER.FACT_TRANSACTIONS (
        TRANSACTION_ID, ACCOUNT_ID, PAYEE_ID, TRANSACTION_DATE, CHECK_NUM,
        DEBIT_AMOUNT, CREDIT_AMOUNT, NET_AMOUNT, TOTAL_CATEGORY_AMOUNT,
        RECEIPT_STATUS, MEMO, STATEMENT_DATES, CLEARED_TYPE, RECONCILED_AT,
        REVIEW_FLAG, _SOURCE_FILE, _INGESTED_AT
    )
    SELECT
        TRANSACTION_ID,
        ACCOUNT_ID,
        PAYEE_ID,
        TRANSACTION_DATE,
        CHECK_NUM,
        DEBIT_AMOUNT,
        CREDIT_AMOUNT,
        (DEBIT_AMOUNT - CREDIT_AMOUNT) AS NET_AMOUNT,
        TOTAL_CATEGORY_AMOUNT,
        RECEIPT_STATUS,
        MEMO,
        STATEMENT_DATES,
        CLEARED_TYPE,
        RECONCILED_AT,
        REVIEW_FLAG,
        _SOURCE_FILE,
        _INGESTED_AT
    FROM FINANCIAL.SILVER.TMP_STAGED_BRONZE;

    -- 3D. Unpivot Splits into a staging CTE for DIM_CATEGORIES & FACT_ACTIVITY_SPLITS
    CREATE OR REPLACE TEMPORARY TABLE FINANCIAL.SILVER.TMP_UNPIVOTED_SPLITS AS
    WITH raw_splits AS (
        SELECT
            t.TRANSACTION_ID,
            t.ACCOUNT_ID,
            t.PAYEE_ID,
            t.TRANSACTION_DATE,
            t.MEMO,
            s.INDEX + 1 AS SPLIT_NUMBER,
            COALESCE(NULLIF(TRIM(s.VALUE:cat::VARCHAR), ''), 'Uncategorized') AS CATEGORY_NAME,
            COALESCE(TRY_TO_NUMBER(
                CASE 
                    WHEN s.VALUE:amt::VARCHAR LIKE '%(%' THEN '-' || REGEXP_REPLACE(s.VALUE:amt::VARCHAR, '[^0-9.]', '')
                    ELSE REGEXP_REPLACE(s.VALUE:amt::VARCHAR, '[^0-9.-]', '')
                END, 12, 2), 0) AS SPLIT_AMOUNT
        FROM FINANCIAL.SILVER.TMP_STAGED_BRONZE t,
        LATERAL FLATTEN(INPUT => ARRAY_CONSTRUCT(
            OBJECT_CONSTRUCT('cat', t.CATEGORY1, 'amt', t.AMOUNT1),
            OBJECT_CONSTRUCT('cat', t.CATEGORY2, 'amt', t.AMOUNT2),
            OBJECT_CONSTRUCT('cat', t.CATEGORY3, 'amt', t.AMOUNT3),
            OBJECT_CONSTRUCT('cat', t.CATEGORY4, 'amt', t.AMOUNT4),
            OBJECT_CONSTRUCT('cat', t.CATEGORY5, 'amt', t.AMOUNT5),
            OBJECT_CONSTRUCT('cat', t.CATEGORY6, 'amt', t.AMOUNT6)
        )) s
        WHERE s.VALUE:cat IS NOT NULL OR s.VALUE:amt IS NOT NULL
    )
    SELECT
        MD5(CONCAT_WS('|', TRANSACTION_ID, TO_VARCHAR(SPLIT_NUMBER))) AS ACTIVITY_SPLIT_ID,
        TRANSACTION_ID,
        ACCOUNT_ID,
        PAYEE_ID,
        MD5(UPPER(CATEGORY_NAME)) AS CATEGORY_ID,
        CATEGORY_NAME,
        SPLIT_NUMBER,
        TRANSACTION_DATE,
        SPLIT_AMOUNT,
        MEMO
    FROM raw_splits;

    -- 3E. Populate DIM_CATEGORIES
    TRUNCATE TABLE FINANCIAL.SILVER.DIM_CATEGORIES;
    INSERT INTO FINANCIAL.SILVER.DIM_CATEGORIES (CATEGORY_ID, CATEGORY_NAME)
    SELECT
        CATEGORY_ID,
        MIN(CATEGORY_NAME) AS CATEGORY_NAME
    FROM FINANCIAL.SILVER.TMP_UNPIVOTED_SPLITS
    GROUP BY CATEGORY_ID;

    -- 3F. Populate FACT_ACTIVITY_SPLITS
    TRUNCATE TABLE FINANCIAL.SILVER.FACT_ACTIVITY_SPLITS;
    INSERT INTO FINANCIAL.SILVER.FACT_ACTIVITY_SPLITS (
        ACTIVITY_SPLIT_ID, TRANSACTION_ID, ACCOUNT_ID, PAYEE_ID, CATEGORY_ID,
        SPLIT_NUMBER, TRANSACTION_DATE, SPLIT_AMOUNT, MEMO
    )
    SELECT
        ACTIVITY_SPLIT_ID,
        TRANSACTION_ID,
        ACCOUNT_ID,
        PAYEE_ID,
        CATEGORY_ID,
        SPLIT_NUMBER,
        TRANSACTION_DATE,
        SPLIT_AMOUNT,
        MEMO
    FROM FINANCIAL.SILVER.TMP_UNPIVOTED_SPLITS;

    RETURN 'Silver layer refresh complete.';
END;
$$;

-- ============================================================================
-- 4. EXECUTE THE REFRESH AND VERIFY COUNTS
-- ============================================================================
CALL FINANCIAL.SILVER.SP_REFRESH_SILVER_LAYER();

SELECT 'DIM_ACCOUNTS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM FINANCIAL.SILVER.DIM_ACCOUNTS
UNION ALL
SELECT 'DIM_PAYEES', COUNT(*) FROM FINANCIAL.SILVER.DIM_PAYEES
UNION ALL
SELECT 'DIM_CATEGORIES', COUNT(*) FROM FINANCIAL.SILVER.DIM_CATEGORIES
UNION ALL
SELECT 'FACT_TRANSACTIONS', COUNT(*) FROM FINANCIAL.SILVER.FACT_TRANSACTIONS
UNION ALL
SELECT 'FACT_ACTIVITY_SPLITS', COUNT(*) FROM FINANCIAL.SILVER.FACT_ACTIVITY_SPLITS;